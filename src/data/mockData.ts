export const GENERATE_PERFORMANCE_HISTORY = (): PerformanceMetric[] => {
  const data: PerformanceMetric[] = [];
  const now = new Date();
  for (let i = 20; i >= 0; i--) {
    const t = new Date(now.getTime() - i * 60000);
    const timeStr = t.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' });
    data.push({
      time: timeStr,
      tps: Number((19.8 + Math.random() * 0.2).toFixed(1)),
      cpu: Math.floor(15 + Math.random() * 8),
      ram: Number((6.1 + Math.random() * 0.5).toFixed(1)),
      players: Math.floor(12 + Math.random() * 4),
      ping: Math.floor(16 + Math.random() * 6),
    });
  }
  return data;
};
